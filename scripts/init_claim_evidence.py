FIELD_REFERENCE = """# SCARF evidence field reference

This is a format guide for the external input template. It does not contain
experimental values. Every digest must be computed from the exact file named by
its adjacent `path` field; never replace a digest with a guessed value.

## Placeholder rules

- `null` means the runner must fill a runtime or measured value.
- `<fill-40-hex-git-commit>` means a lower-case 40-character Git commit.
- `<fill-64-hex-sha256>` means a lower-case SHA256 of the referenced bytes.
- Empty arrays are deliberately incomplete and must be expanded by the run.
- `pending_validation`, `format_only`, `claim_eligible: false`, and
  `synthetic_fixture` are template markers. They must not occur in a claim
  result or in `artifact/reference_results`.

## Calibration

`calibration/manifest.json` is the `dl3dv_calibration_protocol` emitted by
`data/prepare_dl3dv_calibration_inputs.py`. Its two split records must name 24
`calibration_train` and 8 disjoint `calibration_holdout` scenes. Each
representation (`native`, `re10k`) records its prepared input root, index file,
tree/manifest/provenance hashes, selection hash, and sample count. `target_rgb_included`
must remain false for target-free calibration.

`calibration/traces/<split>/<model>_dl3dv/samples/sample_<index>/results.json`
is a `calibration_sample_trace` from `scripts/demo.py --calibration-trace`.
The outer identity is `model`, `dataset`, `sample_index`, `execution_index`,
`scene`, context/target indices, and `seed`. `trace` binds one neural forward,
feature/depth/Gaussian/camera tensor shapes and hashes, candidate scope, and
calibration input hashes. `candidates` contains the complete registered
parameter tuple (`gamma_depth`, `beta_x`, `beta_f`, `beta_d`), quality losses,
fidelity metrics, work/compression reductions, FSDR/SAES event counts, and the
candidate hash. Train uses the global grid; holdout uses only the selected train
tuple.

`calibration/candidates.json` is the split-aware aggregate consumed by
`scripts/calibrate_mechanisms.py`. It binds the calibration manifest, train and
holdout scene/selection/pair/trace/candidate hashes, the selected train
candidate, and the validated holdout candidate. `plan.json`,
`train-candidates.json`, `train-selection.json`, and `holdout-request.json`
preserve the sweep and split decisions needed to audit that aggregate.

`calibration/mechanism_config.json` and `calibration/calibration-result.json`
have the exact shape emitted by `scripts/calibrate_mechanisms.py`. The final
installed copy is `artifact/mechanism_config.json`. It contains the schema
version, `status`, one global `selected` tuple, fixed paper parameters, the
seed-42 LSH ROM binding, the immutable SAES execution identity, the registered
search grid, and `calibration` provenance. A claim-ready file has
`status: calibrated`, `evaluation_disjoint: true`, complete train/holdout
hashes, and a holdout tuple hash equal to the selected tuple.

## Timing backend

`timing-backend/manifest.json` has exactly `schema_version`, `backend`,
`clock_mhz`, and `samples`. `backend.source` identifies the source RTL path
and its SHA256. Each sample entry identifies a model/dataset/index, points to
one raw trace below `timing-backend/timing-trace/`, and contains all four
variants (`asic`, `asic_fsdr`, `asic_saes`, `asic_fsdr_saes`) plus positive
combined `s1`-`s4` cycle counts. The manifest must contain the exact protocol
sample set for the selected profile.

Each raw timing trace has `schema_version: source-bound-timing-trace-v2`, the
model/dataset/index, `cycle_accurate: true`, source RTL SHA256, clock, and one
event for each stage with start/end cycles and acceptance state. The loader
recomputes every trace hash and rejects diagnostic or synthetic traces.

## Workflow results

Every one of the nine `<model>_<dataset>` directories under `quality`,
`mechanisms`, and `speedup` has a sample result and a dataset aggregate. Both
use result schema `2.1`. `provenance` binds source commit/tree, submodules,
command, runtime assets, environment digest, checkpoint/load coverage, dataset
tree/representation, deterministic selection, the frozen mechanism config,
calibration split provenance, and SAES route identity. `quality` contains
baseline/SCARF PSNR/SSIM/LPIPS and per-target-view records. `performance`
contains baseline/SCARF cycles, speedup, component/stage cycles, claim timing,
and the source-bound trace. `events` contains the FSDR and SAES accounting
ledger; `ablation` contains all four timing variants and quality deltas;
`fsdr_saes` records the combined mechanism metrics. `validation` records
reproducibility and must be true/false only in real output.

Sample records carry `execution-trace-inputs-v2` and one trace SHA256. Aggregate
records carry `execution-trace-set-v2`, the sorted sample selection, all sample
evidence paths/hashes, and the aggregate timing trace hash. The claim runner
also stages `timing-trace/<model>/<dataset>/<sample>.json` and a complete
`timing-backend/` bundle below every sample directory.

`pair-execution.json` is the exact `run_pair.py` completion record: `kind`,
sample/executed/resumed/complete counts, and the `source_index` summary
(`source_entry_count`, `null_entry_count`, `sample_count`, source-index SHA256,
and sample-selection SHA256). `progress.jsonl` contains one timestamped JSON
object per pair/sample event; its event shapes are listed in
`progress-event-examples.json`.

## Orin evidence

For every speedup sample, `orin-evidence/measurement.json` is an
`orin_nx_measurement` with the Orin contract and runtime identity, selection
hashes, five positive raw CUDA-event encoder times, their exact median, thermal
limits/samples, and hashes for inference result, CUDA event JSON, tegrastats,
and Nsight files. `cuda-events.json` repeats the five values and median.

The pair-level `orin-profile/pair-measurement.json` is an
`orin_nx_pair_measurement` with the frozen selection hash and one path/hash
entry for every sample measurement. `orin-profile/tegrastats.log` is the raw
text capture containing temperature samples; `orin-profile/nsight.nsys-rep`
is the raw Nsight Systems binary. The measurement loader verifies all hashes
and rejects missing, synthetic, or over-temperature captures.

## Environment and validation

`environments/classic.json`, `depthsplat.json`, and `orin.json` are emitted by
`scripts/check_environment.py`. They contain the profile contract, host
identity, complete runtime details, and UTC generation time. Result provenance
must use the digest computed from the matching environment record.

`validation.json` is written only by `scripts/validate_ae.py --require-key-results`.
It contains the validation profile, `require_key_results: true`, every check
object with actual/target/pass details, and a passed/total summary. A real
claim-ready file has `status: PASS`; this template intentionally does not.

## Expansion counts

Use five-digit zero-padded sample directories. For each model/dataset pair,
the full profile has 6474 Re10K, 1595 ACID, or 140 DL3DV samples; the reviewer
profile has 512, 512, or 140. The same index set must appear in the three
workflow result trees, timing manifest/traces, execution trace sets, and Orin
measurement list. Calibration remains 24 train plus 8 holdout samples per
model-specific DL3DV representation.
"""


def _write_json(path: Path, record: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(record, indent=2, sort_keys=True) + "\n", encoding="utf-8")


