def init(output: Path) -> Path:
    output = _reject_release_output(output)
    output.mkdir(parents=True, exist_ok=True)
    for directory in (
        "calibration",
        "timing-backend/timing-trace",
        "quality",
        "mechanisms",
        "speedup",
    ):
        (output / directory).mkdir(parents=True, exist_ok=True)
    for model in MODELS:
        for dataset in DATASETS:
            pair = f"{model}_{dataset}"
            (output / "quality" / pair).mkdir(parents=True, exist_ok=True)
            (output / "mechanisms" / pair).mkdir(parents=True, exist_ok=True)
            (output / "speedup" / pair).mkdir(parents=True, exist_ok=True)
    (output / "README.md").write_text(README, encoding="utf-8")
    (output / "FORMAT_SPEC.md").write_text(FORMAT_SPEC, encoding="utf-8")
    _write_format_templates(output)
    # These fixtures document the exact interfaces while remaining explicitly
    # rejected by the claim loader.  They are useful when wiring a real export.
    from scripts.build_calibration_validation_fixture import build_fixture as build_calibration_fixture
    from scripts.build_claim_timing_validation_fixture import build_fixture as build_timing_fixture

    build_calibration_fixture(output / "validation-fixtures/calibration")
    build_timing_fixture(output / "validation-fixtures/timing")
    (output / "input-manifest.json").write_text(
        json.dumps(
            {
                "schema_version": "scarf-claim-evidence-input-v1",
                "status": "pending_validation",
                "claim_eligible": False,
                "required_pairs": [f"{model}/{dataset}" for model in MODELS for dataset in DATASETS],
                "required_workflows": ["quality", "mechanisms", "speedup"],
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    return output


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    path = init(args.output)
    print(f"initialized non-claim evidence input template: {path}")
    return 0


