def _reject_release_output(path: Path) -> Path:
    """Keep format templates outside release and generated-evidence roots."""
    resolved = path.resolve()
    forbidden = tuple((ROOT / item).resolve() for item in ("artifact", "outputs", "evidence"))
    if any(resolved == root or root in resolved.parents for root in forbidden):
        raise ValueError(
            "format-only template must be outside artifact/, outputs/, and evidence/"
        )
    return resolved


